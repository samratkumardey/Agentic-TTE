"""Phase 1: recovery of planted effects on synthetic data, as a table comparable with EmulatRx
Table 3 (their Statistician on 1,000 synthetic subjects with planted HRs 0.5, 1, 2, 3).

    uv run python eval/phase1_recovery.py [--n 6000] [--out eval/results]

Writes eval/results/phase1_recovery.md and .json. The truth is the marginal effect from
potential outcomes in each analysis' own population (agentic_tte/synth/dgp.py).
"""

from __future__ import annotations

import json
import sys
import warnings
from pathlib import Path

from agentic_tte.stats import (
    ccw_hr,
    cox_hr,
    iptw_weights,
    match_nearest,
    propensity_scores,
    risk_difference,
    smd,
    subgroup_hrs,
)
from agentic_tte.synth.dgp import Scenario, generate

# EmulatRx, Nat Commun 2026, Table 3 (PSM + Cox, identical across LLMs): planted HR -> estimate
EMULATRX_TABLE3 = {0.5: (0.6345, 0.5448, 0.7389), 1.0: (1.0383, 0.8958, 1.2034),
                   2.0: (1.7524, 1.5152, 2.0267), 3.0: (2.8074, 2.4330, 3.2394)}  # fmt: skip


def ci(h) -> str:
    return f"{h.hr:.3f} ({h.lower:.3f}–{h.upper:.3f})"


def point_scenarios(n: int) -> list[dict]:
    rows = []
    for hr in (0.5, 1.0, 2.0, 3.0):
        c = generate(Scenario(n=n, true_hr=hr))
        f = c.frame.copy()
        ps = propensity_scores(f, c.confounders, "treated")
        f["w"] = iptw_weights(ps, f["treated"])
        m = match_nearest(f, ps, "treated", seed=1)
        matched_truth = c.truth_in(m.data.loc[m.data["treated"] == 1, "person_id"])
        rd = risk_difference(f, c.scenario.horizon_days, weights="w")
        rows.append({
            "planted_conditional_hr": hr,
            "true_marginal_hr": c.truth["marginal_hr"],
            "true_marginal_hr_matched": matched_truth,
            "true_rd": c.truth["risk_difference"],
            "unadjusted": cox_hr(f),
            "iptw": cox_hr(f, weights="w"),
            "psm": cox_hr(m.data, cluster="pair_id"),
            "adjusted_cox": cox_hr(f, covariates=c.confounders),
            "upstream_ridge": cox_hr(f, covariates=c.covariates, weights="w", penalizer=0.1),
            "iptw_rd": rd["risk_difference"],
            "max_smd_weighted": float(smd(f, c.confounders, "treated", f["w"]).max()),
            "matched_share": m.n_matched_treated / m.n_treated,
        })  # fmt: skip
    return rows


def main(argv: list[str]) -> int:
    n = int(argv[argv.index("--n") + 1]) if "--n" in argv else 6000
    out = Path(argv[argv.index("--out") + 1]) if "--out" in argv else Path("eval/results")
    warnings.simplefilter("ignore")
    rows = point_scenarios(n)
    L = ["# Phase 1: recovery of planted effects (synthetic data)\n",
         f"n = {n} per scenario; 28-day horizon; confounding by SOFA, age and lactate; seed "
         f"{Scenario().seed}. Generated by `eval/phase1_recovery.py`. Truths are marginal "
         "effects from potential outcomes; the planted HR is conditional on covariates and "
         "differs from the marginal one (non-collapsibility).\n",
         "## Point treatment (HR, 95% CI)\n",
         "| Planted (conditional) | True marginal | Unadjusted | IPTW + Cox | PSM + Cox "
         "(truth in matched) | Adjusted Cox | Upstream ridge (penalizer 0.1) | EmulatRx Table 3 |",
         "|---|---|---|---|---|---|---|---|"]  # fmt: skip
    for r in rows:
        e = EMULATRX_TABLE3[r["planted_conditional_hr"]]
        L.append(f"| {r['planted_conditional_hr']} | {r['true_marginal_hr']:.3f} | "
                 f"{ci(r['unadjusted'])} | {ci(r['iptw'])} | {ci(r['psm'])} "
                 f"({r['true_marginal_hr_matched']:.3f}) | {ci(r['adjusted_cox'])} | "
                 f"{r['upstream_ridge'].hr:.3f} | {e[0]:.4f} ({e[1]:.4f}–{e[2]:.4f}) |")
    L += ["", "| Planted | True RD (28 d) | IPTW KM RD | Max weighted SMD | Treated matched |",
          "|---|---|---|---|---|"]  # fmt: skip
    for r in rows:
        L.append(f"| {r['planted_conditional_hr']} | {r['true_rd']:+.3f} | {r['iptw_rd']:+.3f} "
                 f"| {r['max_smd_weighted']:.3f} | {100 * r['matched_share']:.0f}% |")  # fmt: skip

    L += ["", "## Treatment started within a grace period (immortal-time setting)\n",
          "| Scenario | Truth (deadline strategy) | Ever-treated (naive) | Clone-censor, unweighted"
          " | Clone-censor-weight |", "|---|---|---|---|---|"]  # fmt: skip
    grace_rows = []
    for label, sc in (
        ("Null, no confounding, grace 7 d", Scenario(n=n, true_hr=1.0, timing="delayed",
                                                     grace_days=7.0, confounding=0.0)),
        ("Null, confounded, grace 3 d", Scenario(n=n, true_hr=1.0, timing="delayed")),
        ("HR 0.5, confounded, grace 3 d", Scenario(n=n, true_hr=0.5, timing="delayed")),
    ):  # fmt: skip
        c = generate(sc)
        naive = cox_hr(c.frame)
        unw = ccw_hr(c.frame, grace=sc.grace_days, covariates=c.confounders, weighted=False)
        ccw = ccw_hr(c.frame, grace=sc.grace_days, covariates=c.confounders)
        t = c.truth["marginal_hr_grace_deadline"]
        grace_rows.append({"scenario": label, "truth": t, "naive": naive, "unweighted": unw,
                           "ccw": ccw})  # fmt: skip
        L.append(f"| {label} | {t:.3f} | {ci(naive)} | {ci(unw)} | {ci(ccw)} |")

    c = generate(Scenario(n=n, modifier_threshold=8))
    f = c.frame.copy()
    f["w"] = iptw_weights(propensity_scores(f, c.confounders, "treated"), f["treated"])
    sg = subgroup_hrs(f, f["sofa"] < 8, labels=("below", "above"), weights="w")
    L += ["", "## Effect modification by SOFA (log HR +0.7 below 8, −0.7 at or above)\n",
          "| Population | True marginal HR | IPTW + Cox |", "|---|---|---|",
          f"| All | {c.truth['marginal_hr']:.3f} | {ci(cox_hr(f, weights='w'))} |",
          f"| SOFA < 8 | {c.truth['marginal_hr_below']:.3f} | {ci(sg['below'])} |",
          f"| SOFA ≥ 8 | {c.truth['marginal_hr_above']:.3f} | {ci(sg['above'])} |", ""]  # fmt: skip

    L += ["## Notes\n",
          "- EmulatRx's synthetic estimates (last column) are attenuated toward HR 1. Two of our "
          "findings bear on that: their Cox model used a ridge penalty (`penalizer=0.1`, here "
          "\"upstream ridge\"), and their comparison used the planted conditional HR as truth, "
          "while IPTW and PSM estimate a marginal HR that is genuinely closer to 1. Their data "
          "and seed differ from ours, so the columns are not directly comparable.",
          "- Clone-censor-weight estimates the grace-period strategy \"start at the natural time "
          "if you would have started, otherwise at the deadline\". \"Everyone starts at a random "
          "time within the grace period\" is a different strategy; both truths are in "
          "`agentic_tte/synth/dgp.py`.",
          "- CIs for weighted Cox models are robust (sandwich). CCW CIs are clustered on the "
          "patient, but do not account for estimating the weights; bootstrap them for "
          "reporting.",
          "- **One sample per row, shared across rows.** All point-treatment scenarios use the "
          "same seed, so the same patients, covariates and treatment assignment; their "
          "estimation errors are correlated. The consistent small upward deviation of IPTW and "
          "PSM (PSM about +0.06 on the log scale) is therefore one observation, not four. Bias "
          "and coverage claims need a Monte Carlo study over many seeds (planned).", ""]
    out.mkdir(parents=True, exist_ok=True)
    (out / "phase1_recovery.md").write_text("\n".join(L), encoding="utf-8")

    def plain(o):
        return o.as_dict() if hasattr(o, "as_dict") else o

    (out / "phase1_recovery.json").write_text(json.dumps(
        {"n": n, "point": [{k: plain(v) for k, v in r.items()} for r in rows],
         "grace": [{k: plain(v) for k, v in r.items()} for r in grace_rows]},
        indent=2), encoding="utf-8")  # fmt: skip
    print(f"wrote {out / 'phase1_recovery.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
